import { defineConfig, devices } from '@playwright/test';

/**
 * Playwright configuration.
 *
 * The E2E suite runs against a real dev server backed by a real MongoDB, with
 * the in-memory storage driver so uploads do not need S3 credentials. It is
 * skipped automatically when `E2E_BASE_URL` is not reachable - see the note in
 * `e2e/README.md`.
 */
